/**
 * 系统默认菜谱（PRD §16.4）
 * ============================================================
 *
 * **这是代码常量，不入库。** `menu_items` 表在 V0.1 只承载「家庭自定义菜谱」。
 * 理由（PRD §16.4）：新家庭进来必须**零配置**就有菜可选 ——
 * 走数据库的话得给每个新家庭灌一遍种子数据，而「第一次打开就能用」是
 * 「吃啥呢」能不能成立的前提。
 *
 * ## 为什么放在后端，而不是 PRD 原来写的 `miniprogram/config/default-menu.ts`
 *
 * 三份文档对齐后可以确定：**后端必须持有这份名单。**
 *   - docs/02 §6.2 `GET /menu/items` 明确返回「系统菜谱 + 本家庭自定义菜谱」的**合集**；
 *   - docs/02 §6.1 `GET /menu/random` 的响应里带 `poolSize`（池子大小）与
 *     `source: "SYSTEM"` —— 池子在后端才算得出来；
 *   - docs/03 P02 明确「进入页面自动随机一次（`GET /menu/random?count=3`）」，
 *     随机与「排除最近吃过的」都在服务端完成。
 *
 * 小程序端**不需要**这份常量（P02 走 `/menu/random`、P17 走 `/menu/items`）。
 * 这一点很重要：小程序端**不能 import `@shared` 的运行时值**（只做类型擦除，
 * 不解析 tsconfig 的 paths），所以一旦有人把这份名单放进 `packages/shared`，
 * 就埋了一个「看着能用、运行时 `MODULE_NOT_FOUND`」的坑。
 * 放在只有后端消费的地方，这个坑就不存在。
 *
 * ## 选菜口径（PRD §16.4）
 *
 * 只收**全国通吃的大众家常菜**。明显带地域偏好的（折耳根、酸菜白肉、三杯鸡……）
 * **不放进来** —— 内置库是「兜底」，不该替某个地方的人做决定。
 * 用户自己加几次菜之后，「吃啥呢」自然贴合本家口味。
 *
 * ## 五个分类是有语义的，不只是标签
 *
 * 「一荤一素一汤」的组合搭配（PRD §16.3）就是靠分类实现的：
 *   - `家常菜` = 荤 → 组合的第 1 道
 *   - `素菜`   = 素 → 组合的第 2 道
 *   - `汤` / `主食` → 组合的第 3 道（汤和主食共用一个位置）
 *   - `外食`   → **不参与组合**（出去吃就不存在「一荤一素」），
 *                只会在「随机 1 道」或组合凑不齐时被抽到
 * 所以改分类会改变推荐行为，不是纯展示调整。
 *
 * ## 为什么写成「菜名 → 分类」的对象，而不是 `[{ name, category }]` 数组
 *
 * **为了让 TypeScript 替我们查重。** 系统菜谱在数据库里没有行，接口上 `id` 恒为
 * `null`，所以**菜名就是唯一标识** —— 而重名会让「排除最近 3 天吃过的」一次误伤
 * 两道菜，症状极轻、极难发现。写成对象字面量后，重名直接是**编译错误**：
 *
 * ```text
 * error TS1117: An object literal cannot have multiple properties with the same name.
 * ```
 *
 * 数组写法只能靠人眼或额外的自查脚本，都不如编译器可靠。
 *
 * 顺带：分类的值写成 `MenuCategory` 联合类型，所以分类打错字也是编译错误。
 * 这两条加起来，这份名单里**没有能静默出错的地方**。
 *
 * ## 菜名还是「最近吃过」的判据
 *
 * 排除最近 3 天吃过的，**按菜名比对** —— 家庭自定义菜谱同样有菜名，
 * 一套判据同时覆盖两种来源，比「系统菜谱用 id、家庭菜谱用 name」干净得多。
 * 代价：改名等于**新增一道菜**（历史 `meal_records` 留的是改名前的快照，这是对的）。
 */

