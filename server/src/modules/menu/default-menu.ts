/**
 * 系统默认菜谱，共 72 条。
 *
 * 顺序 = 上面对象字面量的书写顺序（字符串键的插入顺序是有保证的），
 * 即按分类分组 —— P17 的「系统菜谱」分组直接按这个顺序展示就很好看。
 */
export const SYSTEM_MENU: readonly SystemDish[] = Object.entries(DISH_CATEGORY).map(
  ([name, category]) => ({ name, category }),
);

/** 「荤」的那一类（组合的第 1 道）。 */
export const MEAT_CATEGORY: MenuCategory = '家常菜';
/** 「素」的那一类（组合的第 2 道）。 */
export const VEGGIE_CATEGORY: MenuCategory = '素菜';
/** 组合第 3 道的候选分类（汤和主食共用一个位置）。 */
export const THIRD_CATEGORIES: readonly MenuCategory[] = ['汤', '主食'];
/** 不参与组合的分类。 */
export const DINING_OUT_CATEGORY: MenuCategory = '外食';

/** 按菜名取分类。找不到返回 `null`（家庭自定义菜谱不在本名单里）。 */
export function categoryOfSystemDish(name: string): MenuCategory | null {
  const hit = SYSTEM_MENU.find((dish) => dish.name === name);
  return hit ? hit.category : null;
}
