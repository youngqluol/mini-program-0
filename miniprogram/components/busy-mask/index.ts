/**
 * 提交等待期间的整页遮罩（docs/07 §6.11）
 *
 * 判据只有一条：**等待期间用户还能不能改这份内容**。
 * 能改就要盖住整页 —— 只把按钮变灰的话，等待有好几秒，人还能继续打字、
 * 加图、换可见范围，而发出去的是**按下那一刻**的内容，看到的和发出去的不是一份。
 * 改不出别的（登录、完成一件小事）就只锁按钮，别拿一层纱糊人一脸。
 *
 * 为什么不是 `wx.showLoading`：那是系统白卡片，盖在一页温暖的草稿上很突兀，
 * 而且**它不拦点击** —— 拦不住才是这个组件存在的理由。
 *
 * ⚠️ 遮罩只管吃掉触摸。`textarea` / `input` 在旧渲染层是**原生组件**，
 *    浮在网页层之上，光靠遮罩不一定挡得住聚焦 ——
 *    所以页面里的输入区要另外挂 `disabled="{{提交中那个标记}}"`，两处都要。
 */

